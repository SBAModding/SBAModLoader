#!/usr/bin/env python3
"""Generates the static colour scheme (used when Material You is off or unavailable) from a seed colour.

    pip install materialyoucolor
    python3 scripts/gen_color_scheme.py 7FD1A7

Writes app/src/main/res/values/colors_scheme.xml (light) and values-night/colors_scheme.xml (dark), with the same
tonal-spot scheme Material You uses. The default accent of the app is this seed.
"""
import os
import sys

from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors
from materialyoucolor.hct import Hct
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot

ROLES = [
    'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
    'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
    'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
    'error', 'onError', 'errorContainer', 'onErrorContainer',
    'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
    'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
    'surfaceContainerHigh', 'surfaceContainerHighest',
    'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface', 'inversePrimary',
]


def snake(name):
    out = ''
    for c in name:
        out += ('_' + c.lower()) if c.isupper() else c
    return out


def write(path, seed, dark):
    scheme = SchemeTonalSpot(Hct.from_int(0xFF000000 | seed), dark, 0.0)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by scripts/gen_color_scheme.py (seed #%06X, %s). Do not edit by hand. -->' % (seed, 'dark' if dark else 'light'),
             '<resources>']
    for role in ROLES:
        argb = getattr(MaterialDynamicColors, role).get_argb(scheme)
        lines.append('    <color name="sba_scheme_%s">#%06X</color>' % (snake(role), argb & 0xFFFFFF))
    lines.append('</resources>')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    seed = int(sys.argv[1] if len(sys.argv) > 1 else '7FD1A7', 16)
    res = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'res')
    write(os.path.join(res, 'values', 'colors_scheme.xml'), seed, False)
    write(os.path.join(res, 'values-night', 'colors_scheme.xml'), seed, True)
